const ROWS = 6;
const GAP = '';

/** A character with no drawing in the font becomes blank, so any name still draws something. */
function glyphFor(character: string): readonly string[] {
  return GLYPHS[character] ?? Array<string>(ROWS).fill('   ');
}

/**
 * The banner logo for a word: six rows of block letters. A name too wide for `columns` returns no
 * rows, and the caller shows the plain title only.
 */
export function logoLinesFor(word: string, columns: number): string[] {
  const glyphs = Array.from(word.toUpperCase(), (character) => glyphFor(character));
  if (glyphs.length === 0) return [];
  const rows = Array.from({ length: ROWS }, (_, row) =>
    glyphs.map((glyph) => glyph[row] ?? '').join(GAP),
  );
  const widest = Math.max(...rows.map((line) => line.length));
  return widest <= columns ? rows : [];
}

/** The logo for the configured product name. */
export function brandLogoLines(columns: number): string[] {
  return logoLinesFor(brand.name, columns);
}
